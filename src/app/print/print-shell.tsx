'use client';

import { Printer, X } from 'lucide-react';

/**
 * Shared chrome for the printable documents (receipts and folios). On screen it looks
 * like a sheet of paper with a toolbar; when printing, only the sheet itself survives —
 * the toolbar, navigation and background are removed by the print rules in globals.css.
 */
export function PrintSheet({
  title,
  toolbar,
  children,
}: {
  title: string;
  toolbar?: React.ReactNode;
  children: React.ReactNode;
}) {
  return (
    <div className="min-h-dvh bg-sand-100/70 print:bg-white">
      <div className="no-print sticky top-0 z-10 border-b border-sand-200 bg-white/95 backdrop-blur">
        <div className="mx-auto flex max-w-[52rem] flex-wrap items-center gap-3 px-4 py-2.5">
          <span className="flex min-w-0 flex-1 items-center gap-2">
            <img src="/brand/logo.jpg" alt="" className="h-7 w-7 rounded-md object-cover ring-1 ring-sand-300" />
            <span className="min-w-0">
              <span className="block truncate text-[0.82rem] font-semibold text-navy-800">{title}</span>
              <span className="block text-[0.72rem] text-navy-400">Lemma Apartments · document view</span>
            </span>
          </span>
          <div className="flex min-w-0 w-full flex-wrap items-center gap-2 sm:w-auto">{toolbar}</div>
        </div>
      </div>
      <main className="print-page mx-auto max-w-[52rem] px-3 py-5 sm:px-4 sm:py-8">
        <article className="print-sheet card p-6 sm:p-9">{children}</article>
      </main>
    </div>
  );
}

export function PrintHeader({
  property,
  documentLabel,
  documentNumber,
  issuedOn,
}: {
  property: {
    name: string;
    legalName: string;
    addressLine: string;
    city: string;
    country: string;
    phone: string;
    whatsapp: string;
    email: string;
    website: string;
    taxPayerId: string;
  };
  documentLabel: string;
  documentNumber: string;
  issuedOn: string;
}) {
  return (
    <header className="flex flex-wrap items-start justify-between gap-5 border-b-2 border-navy-800 pb-5">
      <div className="flex min-w-0 items-start gap-3">
        <img src="/brand/logo.jpg" alt={`${property.name} logo`} className="h-14 w-14 shrink-0 rounded-lg object-cover ring-1 ring-sand-300" />
        <div className="min-w-0">
          <p className="font-display text-[1.35rem] leading-tight text-navy-900">{property.name}</p>
          <p className="mt-0.5 text-[0.76rem] leading-snug text-navy-500">
            {property.legalName} · TPIN {property.taxPayerId}
            <br />
            {property.addressLine}, {property.city}, {property.country}
            <br />
            {property.phone} · {property.email} · {property.website.replace(/^https?:\/\//, '')}
          </p>
        </div>
      </div>
      <div className="text-right">
        <p className="text-[0.72rem] font-semibold uppercase tracking-[0.14em] text-navy-400">{documentLabel}</p>
        <p className="mt-1 font-mono text-[1rem] font-bold text-navy-900">{documentNumber}</p>
        <p className="mt-0.5 text-[0.76rem] text-navy-500">Issued {issuedOn}</p>
      </div>
    </header>
  );
}

export function PrintFooter({ lines, signature }: { lines: string[]; signature?: string }) {
  return (
    <footer className="mt-8 border-t border-sand-300 pt-4">
      <ul className="space-y-1 text-[0.74rem] leading-relaxed text-navy-500">
        {lines.map((line) => (
          <li key={line}>{line}</li>
        ))}
      </ul>
      {signature ? (
        <div className="mt-8 flex flex-wrap items-end justify-end gap-8">
          <div className="w-56 border-t border-navy-400 pt-1.5 text-center text-[0.72rem] uppercase tracking-wide text-navy-400">
            {signature}
          </div>
        </div>
      ) : null}
      <p className="mt-6 text-center text-[0.68rem] uppercase tracking-[0.14em] text-navy-300">
        Generated by the Lemma Apartments property system
      </p>
    </footer>
  );
}

export function PrintButton({ label = 'Print' }: { label?: string }) {
  return (
    <button
      type="button"
      onClick={() => window.print()}
      className="btn-primary inline-flex h-9 items-center gap-1.5 px-3 text-[0.82rem]"
    >
      <Printer size={14} /> {label}
    </button>
  );
}

export function CloseLink({ href, label = 'Back' }: { href: string; label?: string }) {
  return (
    <a href={href} className="btn-secondary inline-flex h-9 items-center gap-1.5 px-3 text-[0.82rem]">
      <X size={14} /> {label}
    </a>
  );
}
